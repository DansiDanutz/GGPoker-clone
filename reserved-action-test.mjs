import assert from 'node:assert/strict';
import {reservedChoices,resolveReservedAction} from './betting-preferences.mjs';
const state=(due=0,turn=1)=>({number:1,me:0,hand:{turn,end:null,preAction:{due,call:Math.min(20,due),acted:false,foldEnabled:true}}});
const pick=(kind,call=0)=>({kind,call,number:1,seat:0});
assert.deepEqual(reservedChoices(state().hand.preAction),['check-fold','check']);
assert.deepEqual(reservedChoices(state(4).hand.preAction),['fold','call']);
assert.deepEqual(reservedChoices({...state().hand.preAction,acted:true}),[]);
assert.deepEqual(reservedChoices({...state().hand.preAction,acted:true,reservedCheck:true}),['check-fold'],'Native offers Check/Fold after an anticipated Check');
assert.equal(resolveReservedAction(pick('call',4),state(8)).selection,null,'Changed Call must cancel before the turn');
assert.equal(resolveReservedAction(pick('check'),state(4)).selection,null,'Check must cancel facing a bet');
assert.equal(resolveReservedAction(pick('check-fold'),state(4)).selection.kind,'fold');
assert.equal(resolveReservedAction(pick('check-fold'),state(0,0)).action,'check');
assert.equal(resolveReservedAction(pick('check-fold'),state(4,0)).action,'fold');
assert.equal(resolveReservedAction(pick('call',4),state(4,0)).action,'call');
assert.equal(resolveReservedAction(pick('call',20),state(100,0)).action,'call','Fixed affordable call remains valid for all-in');
for(const changed of [{...state(),number:2},{...state(),me:1},{...state(),hand:null},{...state(),hand:{...state().hand,end:{}}}])assert.deepEqual(resolveReservedAction(pick('check'),changed),{selection:null,action:null});
assert.equal(resolveReservedAction(pick('call',4),state(4)).action,null,'Never act out of turn');
assert.equal(resolveReservedAction(pick('unknown'),state(0,0)).action,null);
const aof=state(0,1);aof.hand.preAction.aof=true;
assert.deepEqual(reservedChoices(aof.hand.preAction),['fold','allin']);
assert.deepEqual(reservedChoices({...aof.hand.preAction,acted:true}),[]);
assert.equal(resolveReservedAction(pick('allin'),aof).action,null);
assert.equal(resolveReservedAction(pick('allin'),{...aof,hand:{...aof.hand,turn:0}}).action,'allin');
assert.equal(resolveReservedAction(pick('fold'),{...aof,hand:{...aof.hand,turn:0}}).action,'fold');
assert.equal(resolveReservedAction(pick('allin'),state(4,0)).action,null,'Normal table must not accept AoF reservation');
assert.equal(resolveReservedAction(pick('call'),aof).selection,null);
const rush=state();rush.hand.preAction.rush=true;
assert.deepEqual(reservedChoices({...rush.hand.preAction,due:4,call:4}),['call']);
assert.deepEqual(reservedChoices({...rush.hand.preAction,bigBlindOption:true}),[]);
assert.equal(resolveReservedAction(pick('check-fold'),{...rush,hand:{...rush.hand,preAction:{...rush.hand.preAction,due:4,call:4}}}).action,'quick-fold','Rush Fold reservation transfers before own turn when a bet appears');
assert.equal(resolveReservedAction(pick('check-fold'),{...rush,hand:{...rush.hand,turn:0}}).action,'check');
console.log('PASS reserved actions: choices, fixed Call cancellation, Check/Fold conversion, own-turn only, all-in cap, hand/seat/end reset');

const own=state(0,0);own.hand.history=[];
const retained=resolveReservedAction({...pick('check-fold'),retain:true},own);
assert.equal(retained.action,'check');assert.ok(retained.selection,'Free native Fold keeps the reservation after checking');
assert.equal(resolveReservedAction(retained.selection,own).action,null,'Repeated paint must not send Check twice');
const later=state(4,0);later.hand.history=['check','raise 4'];assert.equal(resolveReservedAction(retained.selection,later).action,'fold');

const nextFree={...own,hand:{...own.hand,history:['check','check']}};assert.equal(resolveReservedAction(retained.selection,nextFree).action,'check','Retained fold-to-any-bet checks on a later free action');assert.equal(resolveReservedAction(retained.selection,{...nextFree,number:2}).selection,null,'Retained reservation cannot cross hands');
