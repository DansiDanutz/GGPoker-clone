"""Extract private native wheel frames/font/motion; verify decoded pixels and preserve existing outputs."""
import hashlib,io,json,sys,xml.etree.ElementTree as ET
from pathlib import Path
from PIL import Image
root,out=map(Path,sys.argv[1:]);assert root.is_dir() and out.is_dir() and (out/'rea').is_dir()
atlas_path=root/'after_lobby/spinAndGoldWheel.png';atlas_json=atlas_path.with_suffix('.json')
frames=json.loads(atlas_json.read_text(encoding='utf-8-sig'))['frames'];assert len(frames)==15
sources=[atlas_path,atlas_json];records=[]
def save(name,data):
 path=out/name
 if path.exists():assert path.read_bytes()==data,'Preserve differing existing output: '+name
 else:path.write_bytes(data)
 assert path.read_bytes()==data
 records.append({'file':name,'bytes':len(data),'sha256':hashlib.sha256(data).hexdigest()})
with Image.open(atlas_path)as atlas:
 assert atlas.size==(1024,1024)
 for i in range(15):
  entry=frames['spinAndGoldWheel'+str(i).zfill(4)];assert entry['rotated'] is False
  r=entry['frame'];x,y,w,h=(r[k]for k in ['x','y','w','h']);assert all(type(n)is int for n in [x,y,w,h]) and min(x,y)>=0 and min(w,h)>0 and x+w<=atlas.width and y+h<=atlas.height
  pixels=atlas.crop((x,y,x+w,y+h)).convert('RGBA');buffer=io.BytesIO();pixels.save(buffer,format='PNG');name='native-spin-wheel-'+str(i)+'.png';save(name,buffer.getvalue())
  with Image.open(out/name)as actual:assert actual.size==(w,h) and actual.convert('RGBA').tobytes()==pixels.tobytes()
  records[-1].update(frame=[x,y,w,h],rgbaExact=True)
font_path=root/'bmfont/new_spinandgold_normal_wheel.fnt';font=ET.parse(font_path).getroot();page=font.find('pages/page');assert len(font.findall('pages/page'))==1 and page.get('id')=='0'
name=page.get('file');assert name=='new_spinandgold_normal_wheel.png'
png=font_path.parent/'bmfont.png';font_atlas=font_path.parent/'bmfont.xml';sources.extend([font_path,png,font_atlas])
region=ET.parse(font_atlas).getroot().find("SubTexture[@name='new_spinandgold_normal_wheel']");assert region is not None
rect={k:int(region.get(k))for k in ['x','y','width','height']};assert region.get('frameX')=='0' and region.get('frameY')=='0'
common={k:int(v)for k,v in font.find('common').attrib.items()};glyphs=[{k:int(v)for k,v in c.attrib.items()}for c in font.findall('chars/char')];assert len(glyphs)==int(font.find('chars').get('count'))==34 and len({g['id']for g in glyphs})==34 and font.find('info').get('size')=='56'
with Image.open(png)as atlas:
 x,y,w,h=(rect[k]for k in ['x','y','width','height']);assert min(x,y)>=0 and x+w<=atlas.width and y+h<=atlas.height
 image=atlas.crop((x,y,x+w,y+h)).convert('RGBA');assert image.size==(common['scaleW'],common['scaleH'])
 for g in glyphs:assert g['x']>=0 and g['y']>=0 and g['width']>=0 and g['height']>=0 and g['x']+g['width']<=image.width and g['y']+g['height']<=image.height
 buffer=io.BytesIO();image.save(buffer,format='PNG');save('native-spin-wheel-font.png',buffer.getvalue())
 with Image.open(out/'native-spin-wheel-font.png')as actual:assert actual.convert('RGBA').tobytes()==image.tobytes()
 records[-1].update(frame=rect,rgbaExact=True)
save('native-spin-wheel-font.json',(json.dumps({'size':56,'common':common,'glyphs':glyphs},indent=2)+'\n').encode())
motion=root/'spinandgold/spinAndGoldWheelMotion.json';raw=motion.read_bytes();assert hashlib.sha256(raw).hexdigest()=='22fe1566a23475949346cd8548ddb1564c9b363cba41f879b06517c757671c5b';sources.append(motion);save('native-spin-wheel-motion.json',raw)
report={'method':'Native desktop frame-only atlas loader; original bitmap font and motion bytes; no reconstructed trim padding','sources':{str(p):hashlib.sha256(p.read_bytes()).hexdigest()for p in sources},'files':records};save('rea/spin-wheel-art.json',(json.dumps(report,indent=2)+'\n').encode())
print('PASS15 exact native wheel sprites,34 validated font glyphs,original motion hash; '+str(sum(r['bytes']for r in records))+' generated bytes')
